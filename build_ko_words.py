def main():
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ko_words.json")

    # 去重校验：同一韩语词出现多次则报错
    keys = [e[1] for e in ENTRIES]
    dup = [k for k, c in Counter(keys).items() if c > 1]
    if dup:
        raise SystemExit("发现重复词条: " + ", ".join(dup))

    # 生成扁平映射（与 user_words.json 同格式）
    data = {k: v for _, k, v in ENTRIES}
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    # 统计
    cat_cnt = Counter(e[0] for e in ENTRIES)
    print("total_entries =", len(data))
    print("total_categories =", len(cat_cnt))
    for cat, cnt in cat_cnt.items():
        print(f"  {cat}: {cnt}")


if __name__ == "__main__":
    main()
